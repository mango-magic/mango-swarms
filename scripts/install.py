#!/usr/bin/env python3
"""Build four repository-local launchers without downloads or global configuration changes."""

import os
from pathlib import Path
import shlex
import sys
import venv

NAMES = ("swarm-ollama", "swarm-ollama-claude", "swarm-ollama-gpt", "swarm-gpt")
MARKER = "Generated by MangoMagic Swarms"


def install(root):
    if sys.version_info < (3, 9):
        raise RuntimeError("Python 3.9 or newer is required.")
    bindir = root / "bin"
    targets = [bindir / (name + (".cmd" if os.name == "nt" else "")) for name in NAMES]
    for target in targets:
        if target.is_symlink() or (target.exists() and MARKER not in target.read_text(encoding="utf-8")):
            raise RuntimeError("Refusing to overwrite an existing non-MangoMagic launcher: " + str(target))
    environment = root / ".venv"
    if environment.is_symlink():
        raise RuntimeError("Refusing a symlinked .venv.")
    if not environment.exists():
        venv.EnvBuilder(with_pip=False).create(environment)
    python = environment / ("Scripts/python.exe" if os.name == "nt" else "bin/python")
    if not python.is_file():
        raise RuntimeError("Existing .venv is incomplete or from another OS. Rename it and retry.")
    bindir.mkdir(exist_ok=True)
    for target, name in zip(targets, NAMES):
        if os.name == "nt":
            text = ('@echo off\r\nrem ' + MARKER + '\r\n'
                    '"%~dp0..\\.venv\\Scripts\\python.exe" "%~dp0..\\launch.py" ' + name + ' %*\r\n'
                    'exit /b %errorlevel%\r\n')
        else:
            # Resolve the clone at runtime so moving the folder does not break launchers.
            text = ('#!/bin/sh\n# ' + MARKER + '\n'
                    'root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)\n'
                    'exec "$root/.venv/bin/python" "$root/launch.py" ' + name + ' "$@"\n')
        with target.open("w", encoding="utf-8", newline="") as stream:
            stream.write(text)
        target.chmod(0o755)
    print("MangoMagic Swarms installed. Four launchers are ready in " + str(bindir))
    print("No models, provider CLIs, credentials or global settings were installed.")
    if os.name == "nt":
        print(r"Try: .\bin\swarm-ollama.cmd --doctor")
        print(r'Optional, this PowerShell session only: $env:PATH="$PWD\bin;$env:PATH"')
    else:
        print("Try: ./bin/swarm-ollama --doctor")
        print('Optional, this terminal session only: export PATH="$PWD/bin:$PATH"')


if __name__ == "__main__":
    try:
        install(Path(__file__).resolve().parents[1])
    except (OSError, RuntimeError) as error:
        raise SystemExit("MangoMagic setup: " + str(error))
